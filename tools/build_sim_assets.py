#!/usr/bin/env python3
"""
Packs the simulations' shaders and images into plain script files, so the
simulations run when the site is opened straight from disk (no web server).

Run this after you edit any .frag / .vert / .glsl file or replace a colormap or
structure.png:

    python3 tools/build_sim_assets.py

It reads:   assets/sim/shared/Abubu/shaders, assets/sim/shared/Abubu/colormaps,
            assets/sim/ca2d/app/shaders, assets/sim/ca3d/app/shaders, assets/sim/ca3d/app/structure.png
It writes:  assets/sim/shared/assets-common.js
            assets/sim/ca2d/app/assets.js
            assets/sim/ca3d/app/assets.js
"""
import base64, json, os, re, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "assets", "sim")


def read_shaders(folder):
    """Return {file name: source}, with every '#include name' replaced by that file's text."""
    raw = {}
    for name in sorted(os.listdir(folder)):
        if name.endswith((".frag", ".vert", ".glsl")):
            with open(os.path.join(folder, name), encoding="utf-8") as f:
                raw[name] = f.read()

    def expand(src, depth=0):
        if depth > 8:
            raise RuntimeError("include loop")
        def sub(m):
            inc = m.group(1).strip()
            if inc not in raw:
                raise RuntimeError("missing include " + inc + " in " + folder)
            return expand(raw[inc], depth + 1)
        return re.sub(r"#include (.*)", sub, src)

    return {n: expand(s) for n, s in raw.items() if not n.endswith(".glsl")}


def data_uri(path):
    with open(path, "rb") as f:
        return "data:image/png;base64," + base64.b64encode(f.read()).decode("ascii")


def write_js(path, shaders, images, note):
    out = ["/* " + note + " Generated by tools/build_sim_assets.py. Do not edit by hand. */",
           "window.SIM_ASSETS = window.SIM_ASSETS || { shaders: {}, images: {} };"]
    out.append("Object.assign(window.SIM_ASSETS.shaders, " + json.dumps(shaders) + ");")
    out.append("Object.assign(window.SIM_ASSETS.images, " + json.dumps(images) + ");")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", os.path.relpath(path, ROOT), round(os.path.getsize(path) / 1024), "KB")


# --- shared: Abubu shaders and colormaps -------------------------------------
shaders = read_shaders(os.path.join(ROOT, "shared", "Abubu", "shaders"))
images = {}
cm_root = os.path.join(ROOT, "shared", "Abubu", "colormaps")
for dirpath, _, files in os.walk(cm_root):
    for fn in sorted(files):
        if fn.endswith(".png"):
            rel = os.path.relpath(os.path.join(dirpath, fn), os.path.join(ROOT, "shared", "Abubu"))
            images[rel.replace(os.sep, "/")] = data_uri(os.path.join(dirpath, fn))
write_js(os.path.join(ROOT, "shared", "assets-common.js"), shaders, images, "Abubu shaders and colormaps.")

# --- per simulation ------------------------------------------------------------
for sim in ("ca2d", "ca3d"):
    app = os.path.join(ROOT, sim, "app")
    sh = read_shaders(os.path.join(app, "shaders"))
    im = {}
    for fn in sorted(os.listdir(app)):
        if fn.endswith(".png"):
            im[fn] = data_uri(os.path.join(app, fn))
    write_js(os.path.join(app, "assets.js"), sh, im, sim + " shaders and images.")
